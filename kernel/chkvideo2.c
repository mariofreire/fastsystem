uint32_t pci_read_config(uint8_t bus, uint8_t slot, uint8_t func, uint8_t offset) {
    uint32_t address = (uint32_t)((bus << 16) | (slot << 11) | (func << 8) | (offset & 0xFC) | 0x80000000);
    
    // Output the address
    __asm__ volatile("outl %0, %1" : : "a"(address), "Nd"(PCI_CONFIG_ADDRESS));
    
    // Read the data
    uint32_t data;
    __asm__ volatile("inl %1, %0" : "=a"(data) : "Nd"(PCI_CONFIG_DATA));
    
    return data;
}

// Funções inline em Assembly para controle de portas I/O
static inline uint8_t inb(uint16_t port) {
    uint8_t ret;
    __asm__ __volatile__("inb %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

static inline void outb(uint16_t port, uint8_t val) {
    __asm__ __volatile__("outb %0, %1" : : "a"(val), "Nd"(port));
}

static inline uint16_t inw(uint16_t port) {
    uint16_t ret;
    __asm__ __volatile__("inw %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

static inline void outw(uint16_t port, uint16_t val) {
    __asm__ __volatile__("outw %0, %1" : : "a"(val), "Nd"(port));
}

static inline void outl(uint16_t port, uint32_t val) {
    __asm__ volatile("outl %0, %1" : : "a"(val), "Nd"(port));
}

static inline uint32_t inl(uint16_t port) {
    uint32_t ret;
    __asm__ volatile("inl %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

uint32_t pci_read32(uint8_t bus, uint8_t device, uint8_t func, uint8_t offset) {
    uint32_t address = (1U << 31) | (bus << 16) | (device << 11) | 
                       (func << 8) | (offset & 0xFC);
    outl(0xCF8, address);
    return inl(0xCFC);
}

uint16_t pci_get_vendor(uint8_t bus, uint8_t device, uint8_t func) {
    uint32_t reg = pci_read32(bus, device, func, 0x00);
    return (uint16_t)(reg & 0xFFFF);
}

uint16_t pci_get_device(uint8_t bus, uint8_t device, uint8_t func) {
    uint32_t reg = pci_read32(bus, device, func, 0x00);
    return (uint16_t)(reg >> 16);
}

int find_graphics_device(pci_device_t *out_dev) {
    for (int bus = 0; bus < 256; bus++) {
        for (int dev = 0; dev < 32; dev++) {
            for (int func = 0; func < 8; func++) {
                uint16_t vendor = pci_get_vendor(bus, dev, func);
                if (vendor == 0xFFFF) continue; // No device

                // Read Class Code / Subclass from offset 0x08
                uint32_t class_reg = pci_read32(bus, dev, func, 0x08);
                uint8_t class_code = (class_reg >> 24) & 0xFF;

                if (class_code == 0x03) { // Display Controller
                    out_dev->bus = bus;
                    out_dev->device = dev;
                    out_dev->func = func;
                    out_dev->vendor_id = vendor;
                    out_dev->device_id = pci_get_device(bus, dev, func);
                    return 1;
                }
            }
        }
    }
    return 0;
}

uint32_t get_fb_address(uint8_t bus, uint8_t device, uint8_t func) {
	// Example: Read BAR0 to get the physical address of the framebuffer
	// uint32_t bar0 = pci_read_config(bus, slot, func, 0x10);
	// uint32_t framebuffer_paddr = bar0 & 0xFFFFFFF0; // Mask out architecture flags

    // BAR0 is typically at offset 0x10
    uint32_t bar0 = pci_read32(bus, device, func, 0x10);
    return bar0 & 0xFFFFFFF0; // Mask out flags
}

uint32_t get_video_fb_address() {
	find_graphics_device(&video_dev);
	uint32_t fb_addr = get_fb_address(video_dev.bus, video_dev.device, video_dev.func);
	return fb_addr;
}

int getcursor(void)
{
	unsigned short offset;
    outb(0x3d4, 14);
    offset = (inb(0x3d5) << 8);
    outb(0x3d4, 15);
    offset += inb(0x3d5);
	return offset;
}

void setcursoroffset(unsigned short offset)
{
    outb(0x3d4, 14);
    outb(0x3d5, (offset >> 8));
    outb(0x3d4, 15);
    outb(0x3d5, offset);
}

uint16_t bga_read(uint16_t index) {
    outw(VBE_DISPI_IOPORT_INDEX, index);
    return inw(VBE_DISPI_IOPORT_DATA);
}

void bga_write(uint16_t index, uint16_t data) {
    __asm__ volatile("outw %0, %1" : : "a"(index), "Nd"(VBE_DISPI_IOPORT_INDEX));
    __asm__ volatile("outw %0, %1" : : "a"(data), "Nd"(VBE_DISPI_IOPORT_DATA));
}

void clearvga(void)
{
	unsigned long vga_memory_count = VGA_TEXT_ADDRESS;
	unsigned char *vga_memory = (unsigned char *)VGA_TEXT_ADDRESS;
	while (vga_memory_count < (VGA_TEXT_ADDRESS+0xFA0))
	{
		*vga_memory++ = ' ';
		*vga_memory++ = 7;
		vga_memory_count += 2;
	}
	setcursoroffset(0);
	vga = (unsigned char *)VGA_TEXT_ADDRESS;
}

void resetcursor(void) 
{
    // Set cursor position to top left corner
    outb(VGA_CRTC_INDEX, VGA_CURSOR_HIGH);
    outb(VGA_CRTC_DATA, 0);
    outb(VGA_CRTC_INDEX, VGA_CURSOR_LOW);
    outb(VGA_CRTC_DATA, 0);
}

