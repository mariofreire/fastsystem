void printextrgb(long xpos, long ypos, uint32_t fontcolor, uint32_t backcolor, char *name)
{
	long stx, i, x, y, charxsiz;
	char *fontptr, *letptr;

	stx = xpos;

	fontptr = (char*)textfont; charxsiz = 8;

	long xx, yy;
	for(i=0;name[i];i++) {
		letptr = &fontptr[name[i]<<3];
		xx = stx;
		yy = ypos+7 + 2; //+1 is hack!
		for(y=7;y>=0;y--) {
			for(x=charxsiz-1;x>=0;x--) {
				if (letptr[y]&pow2char[7-x])
					setpixel(xx+x,yy,fontcolor);
				else if (backcolor != 0)
					setpixel(xx+x,yy,backcolor);
			}
			yy--;
		}
		stx += charxsiz;
	}

}

void printxy(int x, int y, char *text, int color) {
	printextrgb(x, y, color, 0, text);
}

int printxyf(int x, int y, int color, const char *msg, ...)
{
	//int slen = strlen(msg)*4+1;
	char msgBuf[1024];// = (char*)malloc(slen);
	va_list va_alist;
	int printed = 0;

	if (!msg) return printed;

	//msgBuf[slen - 1] = '\0';
	msgBuf[1024 - 1] = '\0';
	va_start(va_alist, msg);
	printed = vsprintf(msgBuf, msg, va_alist);
	va_end(va_alist);

	printxy(x, y, msgBuf, color);
	
	return printed;	
}

